"""Read GRAD v1 `.grad` files.

A v1 file is CSV with `;` as separator, UTF-8, `.` as decimal separator. GRAD v1 appended a column
`__Формулы__` whose row *i* holds the formula of column *i* (counting every column before it, `Time`
included); all other cells of that column read "no formula". Formulas are returned keyed by parameter
name, with their text untouched. They are never executed: those starting with `data.loc[` were Python
statements that v1 ran through `exec`.

GRAD v1 also generated a `Time` column as whole second + sample index / 1000, which jumps at every
second boundary; `detect_v1_time` recognises it so the user can rebuild time from the sample rate.
"""

import csv
import os
import warnings
from collections import Counter
from collections.abc import Hashable, Mapping
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from types import MappingProxyType
from typing import TYPE_CHECKING

import numpy as np
import pandas as pd

from grad.core.errors import GradFileError, LegacyFormatError

if TYPE_CHECKING:
    from pandas._typing import Dtype, DtypeArg

FORMULAS_COLUMN = "__Формулы__"
NO_FORMULA = "no formula"
LEGACY_PYTHON_PREFIX = "data.loc["
TIME_COLUMN = "Time"
SEPARATOR = ";"
#: utf-8-sig reads plain UTF-8 and also strips a byte-order mark if an editor added one.
ENCODING = "utf-8-sig"
#: Cell texts read as NaN in data columns. v1 (polars) wrote missing values as empty cells and NaN as "NaN".
NA_TOKENS: tuple[str, ...] = ("", "NaN", "nan", "-NaN", "-nan", "NA", "N/A", "null", "NULL", "None")


@dataclass(frozen=True, slots=True)
class LegacyFormula:
    """A formula from a v1 file, text exactly as stored."""

    text: str
    legacy_python: bool
    """True for v1 Python statements (`data.loc[...] = ...`); they are kept as text and never executed."""


class LoadWarningCode(StrEnum):
    NO_FORMULAS_COLUMN = "no_formulas_column"
    """The file has no `__Формулы__` column; every column was loaded as data."""
    UNASSIGNED_FORMULAS = "unassigned_formulas"
    """Formula cells below the last parameter's row were not empty and were ignored."""
    V1_GENERATED_TIME = "v1_generated_time"
    """The `Time` column was generated by v1 and is not uniform; see `LegacyGradFile.v1_time`."""


@dataclass(frozen=True, slots=True)
class LoadWarning:
    code: LoadWarningCode
    message: str


@dataclass(frozen=True, slots=True)
class V1TimePattern:
    """A time column generated by GRAD v1: `start_second + k + i / 1000` for second k and sample i."""

    sample_rate_hz: float
    """Samples per second, i.e. the length of each whole-second run."""
    start_second: int
    repeated_tail: int
    """Number of trailing samples that repeat timestamps of the last whole second (a v1 padding bug)."""


@dataclass(frozen=True, slots=True)
class LegacyGradFile:
    """Content of a v1 `.grad` file."""

    data: pd.DataFrame
    """Data columns, float64, default row index. The formulas column is not included."""
    formulas: Mapping[str, LegacyFormula]
    """Parameter name -> formula, for parameters that had one."""
    time_column: str | None
    """`Time` if the file has such a column, otherwise None."""
    v1_time: V1TimePattern | None
    """Set when the time column follows the v1 generator pattern."""
    warnings: tuple[LoadWarning, ...]


def load_legacy_grad(path: str | os.PathLike[str]) -> LegacyGradFile:
    """Read a GRAD v1 `.grad` file. Formulas are returned as text and never executed.

    Raises `LegacyFormatError` if the content cannot be read as a v1 file and `GradFileError` if the file
    cannot be opened.
    """
    source = Path(path)
    header = _read_header(source)
    load_warnings: list[LoadWarning] = []

    has_formulas = FORMULAS_COLUMN in header
    if has_formulas and header[-1] != FORMULAS_COLUMN:
        raise LegacyFormatError(
            f"{source.name}: column {FORMULAS_COLUMN} must be the last one, as GRAD v1 writes it.",
            source,
            column=FORMULAS_COLUMN,
        )
    data_columns = header[:-1] if has_formulas else header
    if not has_formulas:
        load_warnings.append(
            LoadWarning(
                LoadWarningCode.NO_FORMULAS_COLUMN,
                f"{source.name} has no {FORMULAS_COLUMN} column; all columns were loaded as data.",
            )
        )

    frame = _read_frame(source, header, data_columns)
    if not data_columns:
        data = pd.DataFrame(index=pd.RangeIndex(0))
    elif has_formulas:
        data = frame.drop(columns=[FORMULAS_COLUMN])
    else:
        data = frame

    formulas: dict[str, LegacyFormula] = {}
    if has_formulas:
        cells = frame[FORMULAS_COLUMN].tolist()
        for name, text in zip(data_columns, cells, strict=False):
            if _has_formula(text):
                formulas[name] = LegacyFormula(text, text.lstrip().startswith(LEGACY_PYTHON_PREFIX))
        unassigned = sum(_has_formula(text) for text in cells[len(data_columns) :])
        if unassigned:
            load_warnings.append(
                LoadWarning(
                    LoadWarningCode.UNASSIGNED_FORMULAS,
                    f"{unassigned} formula cell(s) below row {len(data_columns)} of {FORMULAS_COLUMN} belong "
                    "to no parameter and were ignored.",
                )
            )

    time_column = TIME_COLUMN if TIME_COLUMN in data_columns else None
    v1_time = detect_v1_time(data[TIME_COLUMN].to_numpy()) if time_column else None
    if v1_time is not None:
        fs = f"{v1_time.sample_rate_hz:g}"
        tail = (
            f" Its last {v1_time.repeated_tail} samples repeat earlier timestamps."
            if v1_time.repeated_tail
            else ""
        )
        load_warnings.append(
            LoadWarning(
                LoadWarningCode.V1_GENERATED_TIME,
                f"Column {TIME_COLUMN} was generated by GRAD v1 as whole second + sample index / 1000 at "
                f"{fs} samples per second, so it jumps at every second.{tail} "
                f"Rebuild time as arange(n) / {fs}.",
            )
        )

    return LegacyGradFile(
        data=data,
        formulas=MappingProxyType(formulas),
        time_column=time_column,
        v1_time=v1_time,
        warnings=tuple(load_warnings),
    )


def _has_formula(text: object) -> bool:
    # A row with missing trailing fields gives NaN instead of a string: no formula there.
    return isinstance(text, str) and bool(text.strip()) and text != NO_FORMULA


def _read_header(source: Path) -> list[str]:
    """Read column names with the csv module, so duplicates are seen before pandas renames them."""
    try:
        with open(source, encoding=ENCODING, newline="") as file:
            header = next(csv.reader(file, delimiter=SEPARATOR), None)
    except UnicodeDecodeError as exc:
        raise LegacyFormatError(f"{source.name} is not a UTF-8 text file.", source) from exc
    except csv.Error as exc:
        raise LegacyFormatError(f"{source.name}: cannot read the header line: {exc}.", source) from exc
    except OSError as exc:
        raise GradFileError(f"Could not read {source}: {exc.strerror or exc}", source) from exc

    if not header:
        raise LegacyFormatError(f"{source.name} is empty: there is no header line.", source)
    if "" in header:
        position = header.index("") + 1
        raise LegacyFormatError(f"{source.name}: column {position} has no name.", source)
    duplicates = sorted(name for name, count in Counter(header).items() if count > 1)
    if duplicates:
        raise LegacyFormatError(
            f"{source.name}: column names repeat: {', '.join(duplicates)}.", source, column=duplicates[0]
        )
    return header


def _read_csv(
    source: Path, header: list[str], dtype: "DtypeArg", na_values: Mapping[str, list[str]]
) -> pd.DataFrame:
    # With extra fields in a row pandas would either move leading fields into the index (shifting every
    # value) or, with index_col=False, drop the extra ones with only a ParserWarning. Make that an error.
    with warnings.catch_warnings():
        warnings.simplefilter("error", pd.errors.ParserWarning)
        return pd.read_csv(
            source,
            sep=SEPARATOR,
            encoding=ENCODING,
            header=0,
            names=header,
            index_col=False,
            dtype=dtype,
            keep_default_na=False,
            na_values=na_values,
        )


def _read_frame(source: Path, header: list[str], data_columns: list[str]) -> pd.DataFrame:
    dtypes: dict[Hashable, Dtype] = {name: "str" for name in header}
    dtypes.update(dict.fromkeys(data_columns, "float64"))
    try:
        return _read_csv(source, header, dtypes, dict.fromkeys(data_columns, list(NA_TOKENS)))
    except UnicodeDecodeError as exc:
        raise LegacyFormatError(f"{source.name} is not a UTF-8 text file.", source) from exc
    except pd.errors.ParserError as exc:
        raise LegacyFormatError(f"{source.name} is not a valid ';'-separated table: {exc}", source) from exc
    except pd.errors.ParserWarning as exc:
        raise LegacyFormatError(
            f"{source.name} is not a valid ';'-separated table: some lines have more fields than the "
            f"{len(header)} columns of the header.",
            source,
        ) from exc
    except ValueError as exc:
        # A non-numeric cell in a data column. Read everything as text to say where it is.
        text = _read_csv(source, header, "str", {})
        raise _locate_bad_value(source, text, data_columns) from exc
    except OSError as exc:
        raise GradFileError(f"Could not read {source}: {exc.strerror or exc}", source) from exc


def _locate_bad_value(source: Path, text: pd.DataFrame, data_columns: list[str]) -> LegacyFormatError:
    for name in data_columns:
        cells = text[name]
        is_na = cells.isin(NA_TOKENS)
        parsed = np.asarray(pd.to_numeric(cells.where(~is_na), errors="coerce"), dtype=np.float64)
        # to_numeric is only a fast filter; confirm each candidate with float(), which accepts inf etc.
        for row in np.flatnonzero(np.isnan(parsed) & ~is_na.to_numpy()):
            value = cells.iloc[row]
            try:
                float(value)
            except ValueError:
                line = int(row) + 2  # 1-based, after the header line
                return LegacyFormatError(
                    f"{source.name}, line {line}: value {value!r} in column {name!r} is not a number.",
                    source,
                    column=name,
                    line=line,
                )
    return LegacyFormatError(f"{source.name}: some values are not numbers.", source)


def detect_v1_time(values: np.ndarray) -> V1TimePattern | None:
    """Return the v1 pattern if `values` are exactly what GRAD v1 generated, else None.

    v1 built time as `i / 1000 + j` for whole second j (from 1) and sample index i in `range(fs)`. When the
    length was not a multiple of fs it padded the end by repeating the last second's first samples.
    Only 1 < fs < 1000 is reported: then the column is not uniform (fs = 1 and fs = 1000 give uniform
    time). Matching is exact, bit for bit, so genuine recordings are not flagged.
    """
    t = np.asarray(values, dtype=np.float64)
    n = len(t)
    if n < 3 or not np.isfinite(t).all():
        return None
    start = t[0]
    if start != np.floor(start) or start < 0:
        return None
    # fs = length of the first whole-second run.
    later = np.flatnonzero(np.floor(t[1:]) != start)
    if len(later) == 0:
        return None
    fs = int(later[0]) + 1
    if not 1 < fs < 1000:
        return None

    full_seconds, rest = divmod(n, fs)
    sample = np.tile(np.arange(fs, dtype=np.float64), full_seconds)
    second = start + np.repeat(np.arange(full_seconds, dtype=np.float64), fs)
    head = sample / 1000 + second  # same operations, in the same order, as v1
    if not np.array_equal(t[: full_seconds * fs], head):
        return None
    if rest == 0:
        return V1TimePattern(float(fs), int(start), 0)

    tail_sample = np.arange(rest, dtype=np.float64) / 1000
    last_second = start + full_seconds - 1
    if np.array_equal(t[-rest:], tail_sample + last_second):
        return V1TimePattern(float(fs), int(start), rest)
    if np.array_equal(t[-rest:], tail_sample + (last_second + 1)):
        return V1TimePattern(float(fs), int(start), 0)
    return None
